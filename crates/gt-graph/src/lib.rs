//! `gt-graph` —— 提交图泳道布局算法。
//!
//! 这是 Log 视图体验的核心，需求为 FR-LOG-01/05/06，验收标准见
//! 《轻量级Git工具-技术选型与架构规划.md》5.2 与 M0 POC-4。
//!
//! # 设计要点
//!
//! 1. **流式追加**：布局器维护"哪些泳道正在等待哪个提交"的状态，每追加一行只做
//!    O(泳道数) 的工作。分页加载因此不需要重排全图（FR-LOG-01 验收）。
//! 2. **汇合去重**：合并提交会让主干与侧枝两条泳道同时指向汇合点；消费汇合点时
//!    必须把所有等待它的泳道合并到**最早一条**并释放其余，否则泳道数会随合并次数
//!    线性膨胀、单步查找退化为 O(泳道数)（M0 发现并修复的缺陷，见 M0 报告 7.1）。
//! 3. **拓扑序契约**：输入必须满足"子提交先于父提交"。违反该契约时父提交已被消费，
//!    泳道会持续等待永不出现的目标而泄漏（M0 报告 6 节观察 3：峰值泳道从 2 膨胀到
//!    3120）。本模块提供可选的显式校验（M0 待办 #3）。
//!
//! 渲染所需数据全部由 [`RowLayout`] 给出，UI 层不需要理解算法内部状态。

