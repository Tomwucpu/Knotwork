//! `gt-diff` —— 差异计算与 hunk 模型。
//!
//! 采用 Histogram 算法（`imara-diff` / `gix-imara-diff`）：在复杂 diff 上较
//! Myers 快 10%–100%，较 `similar` crate 快至多 30×（架构规划 3.2、附录 B）。
//!
//! 职责边界：
//!
//! - 行级 / 词级差异与 hunk 模型（FR-DIF-01）；
//! - 目录级差异（树比较，FR-DIF-03）；
//! - 流式产出：通过 `Sink` 边算边产出变更块，不物化完整编辑脚本（架构规划 5.6）；
//! - 大文件与二进制阈值判定（单侧 > 2MB 或二进制 → 占位，架构规划 5.5）。
//!
//! 本 crate 在阶段 0 仅完成骨架，实现按实施计划 M1 任务 1-6 落地。
