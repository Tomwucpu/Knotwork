//! `gt-ui` —— UI 组件层。
//!
//! 承载 Slint 组件与各窗口视图：Local Changes、Log + 分支图、Diff、
//! 三路合并编辑器、设置界面（见架构规划 4.1 的分层图）。
//!
//! 设计约束：
//!
//! - **UI 线程零 I/O**：所有数据经 `gt-service` 异步送达，本 crate 只做渲染与交互（架构规划 4.2）；
//! - 列表全虚拟化：Log 只渲染视口内约 40 行（架构规划 5.1）；
//! - 语法高亮惰性化：只对可见行高亮，按行号淘汰缓存（架构规划 5.7）；
//! - 三路合并编辑器与泳道图均为自绘，需与 Slint 保留模式配合。
//!
//! 阶段 0 的 Slint 环境验证在 `app` 的探针窗口中进行；本 crate 自 M1 起承载真实视图。
